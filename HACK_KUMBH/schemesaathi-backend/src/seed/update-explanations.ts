function updateFile(filePath: string) {
  if (!fs.existsSync(filePath)) {
    console.log("File not found:", filePath);
    return;
  }
  const content = fs.readFileSync(filePath, "utf-8");
  const data = JSON.parse(content);

  interface SchemeDoc {
    scheme_id: string;
    overview?: { simple_explanation?: { mr?: string; hi?: string } };
    translation_status?: {
      official_name?: Record<string, string>;
      simple_explanation?: Record<string, string>;
    };
  }

  (data.schemes as SchemeDoc[]).forEach((s) => {
    if (EXPLANATIONS[s.scheme_id]) {
      const exp = EXPLANATIONS[s.scheme_id]!;
      if (!s.overview) s.overview = {};
      if (!s.overview.simple_explanation) s.overview.simple_explanation = {};
      s.overview.simple_explanation.mr = exp.mr;
      s.overview.simple_explanation.hi = exp.hi;

      // Set translation_status to machine_drafted for the 20 schemes
      if (!s.translation_status) {
        s.translation_status = {
          official_name: { en: "reviewed", hi: "reviewed", mr: "reviewed" },
          simple_explanation: { en: "reviewed", hi: "machine_drafted", mr: "machine_drafted" },
        };
      } else if (typeof s.translation_status === "object") {
        if (!s.translation_status.simple_explanation) {
          s.translation_status.simple_explanation = { en: "reviewed", hi: "machine_drafted", mr: "machine_drafted" };
        } else {
          s.translation_status.simple_explanation.mr = "machine_drafted";
          s.translation_status.simple_explanation.hi = "machine_drafted";
        }
      }
    }
  });

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2), "utf-8");
  console.log("Successfully updated:", filePath);
}

